import { test, expect } from '@playwright/test';

test('enter, move, interact, pause, change settings and reset', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'Enter original playground' })).toBeEnabled();
  await page.screenshot({ path: 'artifacts/playground-menu.png' });
  await page.getByRole('button', { name: 'Enter original playground' }).click();
  await expect(page.locator('#hud')).toBeVisible();
  await expect.poll(() => page.evaluate(() => !!document.pointerLockElement)).toBe(true);
  await page.keyboard.press('F3');
  await expect(page.locator('#diagnostics')).toContainText('Grounded');
  await page.keyboard.down('KeyW');
  await expect(page.locator('#prompt')).toContainText('caretaker', { timeout: 10000 });
  await page.keyboard.up('KeyW');
  await page.screenshot({ path: 'artifacts/playground-world.png' });
  await page.keyboard.press('KeyE');
  await expect(page.getByRole('dialog', { name: 'The caretaker' })).toBeVisible();
  await page.getByRole('button', { name: 'Where am I?' }).click();
  await expect(page.locator('#speech')).toContainText('An old courtyard');
  await page.getByRole('button', { name: 'Back to exploring' }).click();
  await expect(page.locator('#hud')).toBeVisible();
  // Browser-level Escape releases pointer lock; explicitly exercise that event in automation.
  await page.evaluate(() => document.exitPointerLock());
  await expect(page.getByRole('heading', { name: 'Paused' })).toBeVisible();
  await page.getByText('Settings', { exact: true }).click();
  await page.getByLabel('Rendering quality').selectOption('low');
  await page.getByLabel('Show collision bounds').check();
  await page.getByRole('button', { name: 'Return to spawn' }).click();
  await expect(page.locator('#diagnostics')).toContainText('0.00, 0.00, 8.00');
  await page.getByRole('button', { name: 'Resume exploring' }).click();
  await expect(page.locator('#hud')).toBeVisible();
  await page.keyboard.press('Space');
  await expect(page.locator('#diagnostics')).toContainText('Airborne');
  await expect(page.locator('#diagnostics')).toContainText('Grounded');
  expect(errors).toEqual([]);
});

test('describe, generate, explore and replace a themed world', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByLabel('Describe your world')).toBeVisible();
  await page.screenshot({ path: 'artifacts/world-creation.png' });
  await page.getByRole('button', { name: 'Candy world', exact: true }).click();
  await page.getByText('Map seed (optional)', { exact: true }).click();
  await page.getByLabel('Seed', { exact: true }).fill('candy-demo');
  await page.getByRole('button', { name: 'Generate world', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Sugarbloom Valley' })).toBeVisible();
  await expect(page.locator('#generation-status')).toContainText('lollipop');
  await expect(page.locator('#generation-status')).toContainText('candy-demo');
  await page.getByRole('button', { name: 'Enter world', exact: true }).click();
  await expect(page.locator('#hud')).toBeVisible();
  await expect(page.locator('#world-name')).toHaveText('Sugarbloom Valley');
  await page.keyboard.press('F3');
  await expect(page.locator('#diagnostics')).toContainText('Grounded');
  await page.keyboard.down('KeyW');
  await expect(page.locator('#prompt')).toContainText('caretaker', { timeout: 10000 });
  await page.keyboard.up('KeyW');
  await page.screenshot({ path: 'artifacts/candy-world.png' });
  await page.keyboard.press('KeyE');
  await expect(page.locator('#speech')).toContainText('Sugarbloom Valley');
  await page.getByRole('button', { name: 'Where am I?' }).click();
  await expect(page.locator('#speech')).toContainText('pink candy world');
  await page.getByRole('button', { name: 'Back to exploring' }).click();
  await expect(page.locator('#hud')).toBeVisible();
  await page.evaluate(() => document.exitPointerLock());
  await page.getByText('Settings', { exact: true }).click();
  await page.getByLabel('Rendering quality').selectOption('low');
  await page.getByLabel('Show collision bounds').check();
  await page.getByRole('button', { name: 'Create another world' }).click();
  await page.getByLabel('Describe your world').fill('A frozen world at night');
  await page.getByRole('button', { name: 'Generate world', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Frostglass Reach' })).toBeVisible();
  await page.getByRole('button', { name: 'Enter world', exact: true }).click();
  await expect(page.locator('#world-name')).toHaveText('Frostglass Reach');
  await expect(page.locator('#diagnostics')).toContainText('0.00, 0.00, 8.00');
  await page.screenshot({ path: 'artifacts/frozen-world.png' });
  await page.evaluate(() => document.exitPointerLock());
  await page.getByRole('button', { name: 'Create another world' }).click();
  await page.getByLabel('Describe your world').fill('<script>alert(1)</script> a city of libraries');
  await page.getByRole('button', { name: 'Generate world', exact: true }).click();
  await expect(page.locator('#generation-status')).toContainText('No supported theme found');
  await page.reload();
  await expect(page.getByLabel('Describe your world')).toBeVisible();
  for (const width of [375, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 800 });
    const fits = await page.locator('#menu').evaluate(dialog => dialog.scrollWidth <= dialog.clientWidth);
    expect(fits, `world form fits viewport width ${width}`).toBe(true);
  }
  expect(errors).toEqual([]);
});
